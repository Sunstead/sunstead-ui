#!/usr/bin/env node
/**
 * Turns the product icons in src/assets/brand/*.svg into components
 * (src/components/brand/*.tsx), so the package stays source-only: a consumer
 * needs no SVG loader. Ids are prefixed per product, so two icons on one page
 * never share a gradient. Run after changing a source:  npm run build:brand
 *
 * The SVGs are copies; sync-brand.mjs refreshes them from the product repos.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@svgr/core';
import jsx from '@svgr/plugin-jsx';
import svgo from '@svgr/plugin-svgo';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const from = path.join(root, 'src/assets/brand');
const to = path.join(root, 'src/components/brand');

const pascal = (id) => id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');

for (const file of readdirSync(from).filter((f) => f.endsWith('.svg')).sort()) {
  const id = file.replace(/\.svg$/, '');
  const name = `${pascal(id)}Mark`;
  const code = await transform(
    readFileSync(path.join(from, file), 'utf8'),
    {
      plugins: [svgo, jsx],
      typescript: true,
      jsxRuntime: 'automatic',
      dimensions: false,
      exportType: 'named',
      namedExport: name,
      svgoConfig: {
        plugins: [
          { name: 'preset-default', params: { overrides: { removeViewBox: false } } },
          { name: 'prefixIds', params: { prefix: `sunstead-${id}`, delim: '-' } },
        ],
      },
      template: ({ jsx: body, componentName }, { tpl }) => tpl`
import type { SVGProps } from 'react';

export function ${componentName}(props: SVGProps<SVGSVGElement>) {
  return ${body};
}
`,
    },
    { componentName: name, filePath: path.join(from, file) },
  );
  writeFileSync(
    path.join(to, `${id}.tsx`),
    `// Generated by scripts/build-brand.mjs from src/assets/brand/${id}.svg. Do not edit.\n${code}`,
  );
  console.log(`${id} -> ${name}`);
}
